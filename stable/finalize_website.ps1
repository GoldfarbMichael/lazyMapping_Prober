<#
.SYNOPSIS
  Windows wrapper for finalize_website.sh -- the equivalent of
    PYTHON_BIN=... H5_LABEL=natalie ./finalize_website.sh 2 180 2288 1 2 4 8 16 32 64 \
        2>&1 | tee web_logs/finalize_website_$(date +%Y%m%d_%H%M%S).log

.DESCRIPTION
  Runs finalize_website.sh under Git Bash (in PowerShell, plain `bash` is WSL's, not Git's) and
  tees its output to stable\web_logs\finalize_website_<yyyyMMdd_HHmmss>.log. Finalize opens no
  browser, so unlike the sweep it can run from SSH (session 0) directly.

  PYTHON_BIN defaults to the repo's .venv (set in finalize_lib.sh); pass -PythonBin to override.

.EXAMPLE
  .\finalize_website.ps1 -H5Label natalie 2 180 2288 1 2 4 8 16 32 64
.EXAMPLE
  .\finalize_website.ps1 -H5Label natalie -DryRun 2 180 2288 1
#>
# PositionalBinding off: every bare argument (TST K CPA NoC...) must land in $FinalizeArgs, not be
# bound by position to -PythonBin / -ExtraEnv.
[CmdletBinding(PositionalBinding = $false)]
param(
    [string]$H5Label = "",
    [string]$PythonBin = "",
    [switch]$DryRun,
    [Alias('Env')][string[]]$ExtraEnv = @(),
    [Parameter(ValueFromRemainingArguments = $true)][string[]]$FinalizeArgs = @()
)
$ErrorActionPreference = 'Stop'

$Stable  = $PSScriptRoot
$GitBash = if ($env:GIT_BASH) { $env:GIT_BASH } else { 'C:\Program Files\Git\bin\bash.exe' }
if (-not (Test-Path $GitBash)) { Write-Host "ERROR: Git Bash not found at '$GitBash' (set GIT_BASH)" -ForegroundColor Red; exit 1 }
if ($FinalizeArgs.Count -lt 4) {
    Write-Host "usage: .\finalize_website.ps1 [-H5Label NAME] [-DryRun] [-PythonBin PATH] <TST> <K> <CPA> <NoC...>" -ForegroundColor Red
    exit 2
}
foreach ($a in $FinalizeArgs) {
    if ($a -notmatch '^[0-9]+$') { Write-Host "ERROR: arguments must be numbers, got '$a'" -ForegroundColor Red; exit 2 }
}

function To-Posix([string]$p) {
    $full = [IO.Path]::GetFullPath($p)
    '/' + $full.Substring(0, 1).ToLower() + $full.Substring(2).Replace('\', '/')
}
function Sh-Quote([string]$s) { "'" + $s.Replace("'", "'\''") + "'" }

$envs = @()
if ($H5Label)   { $envs += "H5_LABEL=$H5Label" }
if ($PythonBin) { $envs += "PYTHON_BIN=$(To-Posix $PythonBin)" }
if ($DryRun)    { $envs += "DRY_RUN=1" }
$envs += $ExtraEnv

# The bash side lives in a temp script: Windows PowerShell 5.1 mangles double quotes inside
# arguments passed to native programs, so an inline `bash -c "..."` is not reliable.
$lines = @('#!/usr/bin/env bash', '# Generated by finalize_website.ps1 -- safe to delete.')
foreach ($kv in $envs) {
    if ($kv -notmatch '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { Write-Host "ERROR: -Env entries must be NAME=VALUE, got '$kv'" -ForegroundColor Red; exit 2 }
    $lines += "export $($Matches[1])=$(Sh-Quote $Matches[2])"
}
$lines += "cd $(Sh-Quote (To-Posix $Stable)) || exit 1"
$lines += 'mkdir -p web_logs'
$lines += 'log="web_logs/finalize_website_$(date +%Y%m%d_%H%M%S).log"'
$lines += 'echo "[finalize] log: stable/$log"'
$lines += './finalize_website.sh "$@" 2>&1 | tee "$log"'
$lines += 'exit "${PIPESTATUS[0]}"'
$runner = Join-Path $env:TEMP 'finalize_website_runner.sh'
[IO.File]::WriteAllText($runner, (($lines -join "`n") + "`n"), (New-Object Text.UTF8Encoding $false))

& $GitBash $runner @FinalizeArgs
exit $LASTEXITCODE
